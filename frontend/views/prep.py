"""Interview Preparation: technical, coding and company-specific question banks."""
import streamlit as st

import api
import data
import state
from state import ss
from ui import badge, card, card_title, chip, empty_state, esc, html, icon, notice, page_header, toast_err, toast_ok

DIFF_KIND = {"easy": "ok", "medium": "warn", "hard": "bad"}
RATING_KIND = {"easy": "ok", "ok": "ok", "hard": "warn", "failed": "bad"}


def _is_company(q: dict, company: str) -> bool:
    cat = (q.get("category") or "").lower()
    return ("company" in cat or "theme" in cat or (company and company.lower() in cat) or (q.get("focus_skill") or "").lower() == "company")


def _diff_ok(q: dict, want: str) -> bool:
    return want in (None, "All") or (q.get("difficulty") or "").lower() == want.lower()


def _details(label: str, inner: str) -> str:
    return f'<details class="pp"><summary>{label}</summary><div class="body">{inner}</div></details>'


def _question_card(i: int, q: dict, prefix: str):
    meta = badge(q["category"], "violet") + badge(q["difficulty"], DIFF_KIND.get(q["difficulty"].lower(), ""))
    if q.get("focus_skill"):
        meta += badge(q["focus_skill"])
    extra = ""
    if q.get("why"):
        extra += _details("Why this is asked", esc(q["why"]))
    if q.get("ideal_points"):
        extra += _details("What a strong answer covers", "<ul style='margin:0;padding-left:1.1rem'>" + "".join(f"<li>{esc(p)}</li>" for p in q["ideal_points"]) + "</ul>")
    with card(f"q-{prefix}-{i}"):
        html(f'<div class="q-head"><div class="q-num">{i}</div><div style="flex:1"><div class="q-text">{esc(q["question"])}</div><div class="q-meta">{meta}</div></div></div>{extra}')


def _log_attempt(sid: str, q: dict, rkey: str):
    rating = ss.get(rkey)
    if not rating:
        return
    try:
        api.log_coding(sid, q["title"], q["topics"], rating)
        state.bump()
        state.log("coding", f"Logged '{q['title']}' as {rating}")
        toast_ok(f"Logged '{q['title']}'. It feeds your roadmap adaptation.")
    except api.ApiError as e:
        toast_err(str(e))


def _coding_card(i: int, q: dict, sid: str, logged: dict):
    meta = badge(q["difficulty"], DIFF_KIND.get(q["difficulty"].lower(), "")) + "".join(badge(t) for t in q["topics"])
    if q.get("expected_complexity"):
        meta += badge("Target: " + q["expected_complexity"], "cyan")
    prev = logged.get(q["title"])
    if prev:
        meta += badge(f"Last logged: {prev['rating']}", RATING_KIND.get(prev["rating"], ""))
    extra = ""
    if q.get("example"):
        extra += f'<div class="codebox mono" style="margin-top:.6rem">{esc(q["example"])}</div>'
    if q.get("hint"):
        extra += _details("Show hint", esc(q["hint"]))
    if q.get("why"):
        extra += _details("Why this problem", esc(q["why"]))
    with card(f"c-{i}"):
        html(f'<div class="q-head"><div class="q-num">{i}</div><div style="flex:1"><div class="q-text">{esc(q["title"])}</div>'
             f'<div style="font-size:14px;color:var(--muted);line-height:1.6;margin-top:.35rem">{esc(q["statement"])}</div><div class="q-meta">{meta}</div></div></div>{extra}')
        rkey = f"rate-{sid}-{i}"
        c1, c2 = st.columns([3.2, 1], vertical_alignment="bottom")
        with c1:
            st.segmented_control("How did it go?", ["easy", "ok", "hard", "failed"], key=rkey, default=None,
                                 format_func=lambda x: {"easy": "Easy", "ok": "Solved", "hard": "Hard", "failed": "Couldn't solve"}[x])
        c2.button("Log attempt", key=f"log-{sid}-{i}", type="secondary", width="stretch", disabled=not ss.get(rkey),
                  on_click=_log_attempt, args=(sid, q, rkey))


def render():
    page_header("Interview Preparation", "Your question bank",
                "Questions generated from your resume, your skill gaps and the target company. Log coding attempts so your roadmap adapts to what is hard.")
    A = ss.analysis
    if not A:
        empty_state("quiz", "No questions yet", "Run an analysis first. Questions are generated from your resume, the job description and the company you target.")
        st.button("Go to Resume Analyzer", key="pp-cta", type="primary", on_click=state.new_analysis)
        return

    sid = state.sid()
    company = (A.get("company") or "").strip()
    iq, cq = A["interview_questions"], A["coding_questions"]
    tech = [q for q in iq if not _is_company(q, company)]
    comp = [q for q in iq if _is_company(q, company)]
    html(f'<div style="display:flex;gap:.5rem;flex-wrap:wrap;margin:-.2rem 0 .3rem">'
         f'{badge("Generated by " + ("Groq LLM" if A["generation_mode"] == "groq" else "rule-based engine (offline)"), "violet" if A["generation_mode"] == "groq" else "warn")}'
         f'{badge(f"{len(iq)} interview questions")}{badge(f"{len(cq)} coding problems")}</div>')

    dash = data.dash(sid, ss.rev)
    logged = {}
    if dash:
        for e in dash["coding"]["log"]:
            logged[e["title"]] = e

    t1, t2, t3 = st.tabs([f"Technical ({len(tech)})", f"Coding ({len(cq)})", f"Company-specific ({len(comp)})"])
    with t1:
        diff = st.segmented_control("Difficulty", ["All", "Easy", "Medium", "Hard"], default="All", key="prep-diff-t")
        shown = [q for q in tech if _diff_ok(q, diff)]
        if not shown:
            empty_state("quiz", "No questions at this difficulty", "Choose another difficulty filter.")
        for i, q in enumerate(shown, 1):
            _question_card(i, q, "t")
    with t2:
        diff = st.segmented_control("Difficulty", ["All", "Easy", "Medium", "Hard"], default="All", key="prep-diff-c")
        shown = [(i, q) for i, q in enumerate(cq, 1) if _diff_ok(q, diff)]
        if not shown:
            empty_state("code", "No problems at this difficulty", "Choose another difficulty filter.")
        for i, q in shown:
            _coding_card(i, q, sid, logged)
    with t3:
        kb = A["context"]["company_kb"]
        generic = kb["matched_by"] == "fallback"
        with card("kb"):
            card_title(f"Hiring context: {kb['company']}", "building")
            how = {"name": "matched by company name", "semantic": "matched by semantic search", "fallback": "general hiring pattern (company not recognised)"}[kb["matched_by"]]
            html(f'<div style="margin-top:-.2rem">{badge(how, "violet" if not generic else "warn")}</div>'
                 f'<div style="font-size:14px;line-height:1.6;color:var(--muted)">{esc(kb["process"])}</div>'
                 f'<div class="faint" style="font-size:12px;margin-top:.2rem">FOCUS AREAS</div><div>{"".join(chip(f) for f in kb["focus"])}</div>'
                 + (f'<div class="faint" style="font-size:12px;margin-top:.3rem">COMMONLY SEEN THEMES</div><ul style="margin:.2rem 0 0;padding-left:1.1rem;color:var(--muted);font-size:13.5px;line-height:1.7">'
                    + "".join(f"<li>{esc(t)}</li>" for t in kb["themes"]) + "</ul>" if kb.get("themes") else "")
                 + '<div class="faint" style="font-size:11.5px;margin-top:.5rem">Seed knowledge of general hiring patterns, not official company statements. Extend backend/app/data/company_kb.json for better grounding.</div>')
        if not company:
            notice("info", "You did not enter a target company, so only general hiring patterns are shown. Add one in a new analysis for tailored questions.")
        for i, q in enumerate(comp, 1):
            _question_card(i, q, "c")
        if company and not comp:
            notice("info", "None of the generated questions are tagged as company-specific in this run. The themes above come from the company knowledge base.")
