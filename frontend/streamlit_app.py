"""PlacementPilot: application shell (sidebar, top bar, routing). Page content lives in views/."""
import streamlit as st

st.set_page_config(page_title="PlacementPilot", page_icon=":material/explore:", layout="wide", initial_sidebar_state="expanded")

import api  # noqa: E402
import data  # noqa: E402
import state  # noqa: E402
import theme  # noqa: E402
from state import PAGES, PAGE_LABEL, ss  # noqa: E402
from ui import esc, html, icon, toast_err, toast_ok  # noqa: E402
from views import analytics, analyzer, mock_interview, overview, prep, roadmap, skills  # noqa: E402

theme.inject()
state.init()

VIEWS = {"overview": overview, "analyzer": analyzer, "skills": skills, "prep": prep,
         "mock": mock_interview, "roadmap": roadmap, "analytics": analytics}

health = data.health()


def mode_pill() -> str:
    if health is None:
        return '<span class="pill bad"><span class="dot"></span>Backend unreachable</span>'
    if health["llm_mode"] == "groq":
        return '<span class="pill violet" title="Questions, roadmap and interview scoring are generated by Groq LLM"><span class="dot"></span>AI-powered</span>'
    return '<span class="pill warn" title="No GROQ_API_KEY configured: rule-based generation is used"><span class="dot"></span>Offline mode</span>'


def delete_data():
    sid = state.sid()
    try:
        api.delete_session(sid)
        toast_ok("Your resume and all derived data were deleted.")
    except api.ApiError as e:
        toast_err(str(e))
    data._plan.clear(); data._dash.clear()
    state.reset_all()


# ---------------------------------------------------------------- routing
# Native multipage routing (hidden built-in menu): every section has its own URL and the browser Back/Forward buttons work.
pages = {key: st.Page(VIEWS[key].render, title=label, icon=mic, url_path=key, default=(key == "overview")) for key, label, mic in PAGES}
pg = st.navigation(list(pages.values()), position="hidden")
target = ss.pop("nav_to", None)
if target and pages[target] is not pg:
    st.switch_page(pages[target])
current_key = next(k for k, p in pages.items() if p is pg)

# ------------------------------------------------------------------ sidebar
def nav_marks() -> dict[str, tuple[str, str]]:
    """Status marker per section: key -> (kind, text). Only real data; a section with nothing to report gets no marker."""
    A = ss.analysis
    if not A:
        return {}
    marks = {"analyzer": ("ok", "Analysis complete")}
    gaps = len(A["skills"]["missing"]) + len(A["skills"]["weak"])
    marks["skills"] = ("count", str(gaps)) if gaps else ("ok", "No skill gaps")
    dash = data.dash(state.sid(), ss.rev)
    if dash:
        n = len(dash["mock_hr_history"])
        if n:
            marks["mock"] = ("ok", f"{n} interview{'s' if n != 1 else ''} completed")
        left = dash["tasks_total"] - dash["tasks_done"]
        marks["roadmap"] = ("count", str(left)) if left else ("ok", "All tasks done")
        if dash["coding"]["attempted"]:
            marks["prep"] = ("count", str(dash["coding"]["attempted"]))
    return marks


def mark_html(kind: str, text: str, key: str) -> str:
    tips = {"skills": "skill gaps to close", "roadmap": "roadmap tasks left", "prep": f"of {len(ss.analysis['coding_questions']) if ss.analysis else 0} coding problems attempted"}
    tip = text if kind == "ok" else f"{text} {tips.get(key, '')}"
    inner = icon("check", 11, 2.6) if kind == "ok" else esc(text)
    return f'<span class="navmark {kind}" title="{esc(tip)}">{inner}</span>'


with st.sidebar:
    html(f'<div class="pp-brand"><div class="mark" style="color:#fff">{icon("logo", 17)}</div>'
         f'<div class="word">Placement<b>Pilot</b></div></div><div class="pp-navlabel">Workspace</div>')
    marks = nav_marks()
    for key, label, mic in PAGES:
        with st.container(key="navactive" if key == current_key else f"navitem-{key}"):
            st.page_link(pages[key], label=label, icon=mic)
            if key in marks:
                html(mark_html(*marks[key], key))
    rows = ""
    if health:
        rows += f'<div class="row"><span>Engine</span><b>{"Groq LLM" if health["llm_mode"] == "groq" else "Rule-based"}</b></div>'
        emb = "HF embeddings" if health["embedding_backend"] != "hashing-fallback" else "Hashing fallback"
        rows += f'<div class="row"><span>Embeddings</span><b>{emb}</b></div>'
    else:
        rows += '<div class="row"><span>Backend</span><b style="color:var(--bad)">Offline</b></div>'
    rows += f'<div class="row"><span>Session</span><b>{esc(state.sid()) if state.sid() else "None"}</b></div>'
    html(f'<div class="pp-sidefoot">{rows}</div>')
    if state.sid():
        st.button("Delete my data", key="side-danger", icon=":material/delete:", width="stretch", type="tertiary", on_click=delete_data,
                  help="Erases your resume text, analysis, interviews and progress from the backend.")

# ----------------------------------------------------------------- top bar
html(f'<div class="pp-top"><div class="pp-crumb"><span>PlacementPilot</span>{icon("chevron", 13)}<b>{esc(PAGE_LABEL[current_key])}</b></div>'
     f'<div class="pp-top-right">{mode_pill()}</div></div>')

# Narrow screens: the sidebar is collapsed by default, so offer the same menu at the top of the page (CSS shows it only < 900px).
with st.container(key="mobilenav"):
    labels = {label: key for key, label, _ in PAGES}
    st.pills("Navigate", list(labels), selection_mode="single", default=PAGE_LABEL[current_key], key=f"w_mnav_{current_key}",
             label_visibility="collapsed", on_change=lambda: ss.__setitem__("nav_to", labels.get(ss.get(f"w_mnav_{current_key}") or "", None)))

    if state.sid():
        st.button("Delete my data", key="mobile-delete", icon=":material/delete:", type="tertiary", on_click=delete_data)

if health is None:
    st.markdown(
        '<div class="notice bad" style="margin-bottom:1rem"><div><b>Cannot reach the backend.</b> Start it with <code>./run_backend.sh</code> '
        f'(expected at <code>{esc(api.API_URL)}</code>).</div></div>', unsafe_allow_html=True)

pg.run()
